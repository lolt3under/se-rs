fn cases() -> impl Iterator<Item = &'static Case> {
    [GREP_CASES, RIPGREP_CASES, SED_CASES, AWK_CASES]
        .into_iter()
        .flatten()
}

fn known(id: &str) -> Option<&'static KnownFailure> {
    KNOWN_FAILURES.iter().find(|failure| failure.id == id)
}

fn run(case: &Case) -> Output {
    let mut child = Command::new(env!("CARGO_BIN_EXE_se"))
        .arg(case.program)
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .unwrap_or_else(|error| panic!("{}: failed to spawn se: {error}", case.id));
    child
        .stdin
        .take()
        .expect("piped stdin")
        .write_all(case.input)
        .unwrap_or_else(|error| panic!("{}: failed to write stdin: {error}", case.id));
    child
        .wait_with_output()
        .unwrap_or_else(|error| panic!("{}: failed to wait for se: {error}", case.id))
}

fn desired_mismatch(case: &Case, output: &Output) -> Option<String> {
    let success = output.status.success();
    if success == case.expected_success
        && (!case.expected_success || output.stdout == case.expected_stdout)
        && (!case.expected_success || output.stderr.is_empty())
    {
        return None;
    }
    Some(format!(
        "{} [{:?}; {}]\n  program: {:?}\n  input: {}\n  expected: success={}, stdout={}\n  actual: success={}, code={:?}, stdout={}, stderr={}",
        case.id,
        case.family,
        case.origin,
        case.program,
        bytes(case.input),
        case.expected_success,
        bytes(case.expected_stdout),
        success,
        output.status.code(),
        bytes(&output.stdout),
        bytes(&output.stderr),
    ))
}

fn bytes(value: &[u8]) -> String {
    if let Ok(text) = std::str::from_utf8(value) {
        format!("{text:?}")
    } else {
        let hex = value
            .iter()
            .map(|byte| format!("{byte:02x}"))
            .collect::<Vec<_>>()
            .join(" ");
        format!("<non-UTF-8: {hex}>")
    }
}

#[test]
fn static_compatibility_corpus() {
    let mut failures = Vec::new();
    let mut checked = 0usize;
    for case in cases().filter(|case| known(case.id).is_none()) {
        checked += 1;
        let output = run(case);
        if let Some(mismatch) = desired_mismatch(case, &output) {
            failures.push(mismatch);
        }
    }
    assert!(
        failures.is_empty(),
        "{}/{} undocumented compatibility cases failed:\n\n{}",
        failures.len(),
        checked,
        failures.join("\n\n"),
    );
}

