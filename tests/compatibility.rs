fn documented_known_failures_are_stable() {
    let mut failures = Vec::new();
    for expected in KNOWN_FAILURES {
        let Some(case) = cases().find(|case| case.id == expected.id) else {
            failures.push(format!("{}: no corresponding static Case", expected.id));
            continue;
        };
        let output = run(case);
        let actual_success = output.status.success();
        let actual_stderr = String::from_utf8_lossy(&output.stderr);
        if actual_success != expected.actual_success
            || output.stdout != expected.actual_stdout
            || !actual_stderr.contains(expected.stderr_contains)
        {
            failures.push(format!(
                "{} changed\n  pinned actual: success={}, stdout={}, stderr contains {:?}\n  new actual: success={}, code={:?}, stdout={}, stderr={}",
                expected.id,
                expected.actual_success,
                bytes(expected.actual_stdout),
                expected.stderr_contains,
                actual_success,
                output.status.code(),
                bytes(&output.stdout),
                bytes(&output.stderr),
            ));
        }
        if desired_mismatch(case, &output).is_none() {
            failures.push(format!(
                "{} now passes its desired compatibility expectation; remove it from KNOWN_FAILURES and the Markdown ledger",
                expected.id
            ));
        }
    }
    assert!(
        failures.is_empty(),
        "{} known-failure baselines changed:\n\n{}",
        failures.len(),
        failures.join("\n\n"),
    );
}

// Run this ignored test explicitly for the intentional red-suite audit.
// A non-zero result is expected until every ledger entry is fixed.
#[test]
#[ignore = "intentional red suite; see docs/compatibility.md"]
fn full_compatibility_audit() {
    let mut failures = Vec::new();
    let mut checked = 0usize;
    for case in cases() {
        checked += 1;
        let output = run(case);
        if let Some(mismatch) = desired_mismatch(case, &output) {
            failures.push(mismatch);
        }
    }
    assert!(
        failures.is_empty(),
        "{}/{} compatibility cases failed:\n\n{}",
        failures.len(),
        checked,
        failures.join("\n\n"),
    );
}
