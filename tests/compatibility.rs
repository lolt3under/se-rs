//! Static compatibility corpus translated from grep, ripgrep, sed, and awk.
//!
//! These are deliberately data-driven: every vector is a compile-time constant,
//! the full audit reports all mismatches in one run, and known failures remain
//! executable instead of being deleted or weakened. See `docs/compatibility.md`.

use std::io::Write;
use std::process::{Command, Output, Stdio};

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
enum Family {
    Grep,
    Ripgrep,
    Sed,
    Awk,
}

#[derive(Clone, Copy)]
struct Case {
    id: &'static str,
    family: Family,
    origin: &'static str,
    program: &'static str,
    input: &'static [u8],
    expected_stdout: &'static [u8],
    expected_success: bool,
}

const fn ok(
    id: &'static str,
    family: Family,
    origin: &'static str,
    program: &'static str,
    input: &'static [u8],
    expected_stdout: &'static [u8],
) -> Case {
    Case {
        id,
        family,
        origin,
        program,
        input,
        expected_stdout,
        expected_success: true,
    }
}

const fn err(
    id: &'static str,
    family: Family,
    origin: &'static str,
    program: &'static str,
    input: &'static [u8],
) -> Case {
    Case {
        id,
        family,
        origin,
        program,
        input,
        expected_stdout: b"",
        expected_success: false,
    }
}

